-- DimDate: 2016-01-01 .. 2018-12-31 + unknown
INSERT INTO project_dw.dim_date
SELECT TO_CHAR(d, 'YYYYMMDD')::INT, d, EXTRACT(DAY FROM d), TRIM(TO_CHAR(d, 'Day')), EXTRACT(ISODOW FROM d),
       EXTRACT(ISODOW FROM d) IN (6, 7), EXTRACT(WEEK FROM d), TO_CHAR(d, 'IYYY-"W"IW'),
       EXTRACT(MONTH FROM d), TRIM(TO_CHAR(d, 'Month')), TO_CHAR(d, 'YYYY-MM'),
       EXTRACT(QUARTER FROM d), 'Q' || EXTRACT(QUARTER FROM d) || ' ' || EXTRACT(YEAR FROM d), EXTRACT(YEAR FROM d)
FROM generate_series('2016-01-01'::DATE, '2018-12-31'::DATE, '1 day') AS g(d)
ON CONFLICT (date_key) DO NOTHING;
