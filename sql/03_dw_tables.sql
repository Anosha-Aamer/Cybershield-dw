INSERT INTO project_dw.dim_time
SELECT h * 100 + m, h, m, LPAD(h::TEXT, 2, '0') || ':' || LPAD(m::TEXT, 2, '0'),
       CASE WHEN h < 6 THEN 'Night' WHEN h < 12 THEN 'Morning' WHEN h < 17 THEN 'Afternoon'
            WHEN h < 21 THEN 'Evening' ELSE 'Night' END
FROM generate_series(0, 23) h CROSS JOIN generate_series(0, 59) m
