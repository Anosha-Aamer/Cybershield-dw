-- =====================================================================
-- 03  Warehouse star schema (schema project_dw)
--   * Every dimension has an INT IDENTITY surrogate key + a UNIQUE natural (business) key
--   * Key -1 = 'Unknown' member (missing values, milestones not reached)
--   * DimDate / DimTime use smart keys (YYYYMMDD / HHMM) and are generated, not loaded
--   * SCD Type 1 everywhere (source keeps no history)
-- =====================================================================

-- ---------------- DIMENSIONS ----------------
CREATE TABLE IF NOT EXISTS project_dw.dim_date (
    date_key            INT PRIMARY KEY,           -- YYYYMMDD, -1 = unknown / not reached
    full_date           DATE,
    day_of_month        SMALLINT,
    day_name            VARCHAR(10),
    day_of_week_number  SMALLINT,                  -- 1 = Monday ... 7 = Sunday (ISO)
    is_weekend          BOOLEAN,
    week_of_year        SMALLINT,                  -- ISO week
    year_week           VARCHAR(8),                -- '2016-W09' (unique across years)
    month_number        SMALLINT,
    month_name          VARCHAR(10),
    year_month          VARCHAR(7),                -- '2016-03'
    quarter_number      SMALLINT,
    quarter_name        VARCHAR(7),                -- 'Q1 2016'
    year_number         SMALLINT
);

CREATE TABLE IF NOT EXISTS project_dw.dim_time (
    time_key     INT PRIMARY KEY,                  -- HHMM (0..2359), -1 = unknown
    hour24       SMALLINT,
    minute       SMALLINT,
    time_label   VARCHAR(5),                       -- '13:45'
    time_period  VARCHAR(20)                       -- Night / Morning / Afternoon / Evening
);

CREATE TABLE IF NOT EXISTS project_dw.dim_location (
    location_key   INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    location_code  VARCHAR(30) NOT NULL UNIQUE,     -- natural key: 'Location 143'
    site_name      VARCHAR(100) NOT NULL,
    city           VARCHAR(50) NOT NULL,
    province       VARCHAR(50) NOT NULL,
    region         VARCHAR(50) NOT NULL,
    country        VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS project_dw.dim_category (
    category_key      INT GENERATED BY DEFAULT AS IDENTITY (START WITH 2001) PRIMARY KEY,
    category_code     VARCHAR(30) NOT NULL,         -- natural key part 1: 'Category 26'
    subcategory_code  VARCHAR(30) NOT NULL,         -- natural key part 2: 'Subcategory 174'
    attack_family     VARCHAR(50) NOT NULL,
    category_name     VARCHAR(100) NOT NULL,
    subcategory_name  VARCHAR(150) NOT NULL,
    CONSTRAINT uq_dim_category UNIQUE (category_code, subcategory_code)
);

CREATE TABLE IF NOT EXISTS project_dw.dim_severity (
    severity_key      INT GENERATED BY DEFAULT AS IDENTITY (START WITH 3001) PRIMARY KEY,
    priority_level    VARCHAR(20) NOT NULL,          -- natural key: priority + impact + urgency
    impact_level      VARCHAR(20) NOT NULL,
    urgency_level     VARCHAR(20) NOT NULL,
    priority_number   SMALLINT,                      -- 1 Critical ... 4 Low
    is_high_severity  BOOLEAN NOT NULL,              -- priority 1 or 2
    CONSTRAINT uq_dim_severity UNIQUE (priority_level, impact_level, urgency_level)
);

CREATE TABLE IF NOT EXISTS project_dw.dim_status (
    status_key    INT GENERATED BY DEFAULT AS IDENTITY (START WITH 4001) PRIMARY KEY,
    status_name   VARCHAR(30) NOT NULL UNIQUE,       -- natural key: incident_state
    status_group  VARCHAR(20) NOT NULL,              -- Open / Waiting / Resolved / Closed
    is_open_flag  BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS project_dw.dim_response_team (
    team_key    INT GENERATED BY DEFAULT AS IDENTITY (START WITH 5001) PRIMARY KEY,
    team_code   VARCHAR(30) NOT NULL UNIQUE,         -- natural key: assignment_group 'Group 56'
    team_name   VARCHAR(60) NOT NULL                 -- 'Response Team 56'
);

CREATE TABLE IF NOT EXISTS project_dw.dim_contact_type (
    contact_type_key   INT GENERATED BY DEFAULT AS IDENTITY (START WITH 6001) PRIMARY KEY,
    contact_type_name  VARCHAR(30) NOT NULL UNIQUE   -- natural key: contact_type
);

-- ---------------- FACTS ----------------
-- Transaction fact: one row per reported incident (attributes as reported)
CREATE TABLE IF NOT EXISTS project_dw.fact_incident (
    incident_key        BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 100001) PRIMARY KEY,
    incident_number     VARCHAR(15) NOT NULL UNIQUE,                 -- degenerate dimension
    caller_id           VARCHAR(30),                                 -- degenerate dimension
    reported_date_key   INT NOT NULL REFERENCES project_dw.dim_date(date_key),
    reported_time_key   INT NOT NULL REFERENCES project_dw.dim_time(time_key),
    location_key        INT NOT NULL REFERENCES project_dw.dim_location(location_key),
    category_key        INT NOT NULL REFERENCES project_dw.dim_category(category_key),
    severity_key        INT NOT NULL REFERENCES project_dw.dim_severity(severity_key),
    contact_type_key    INT NOT NULL REFERENCES project_dw.dim_contact_type(contact_type_key),
    incident_count      SMALLINT NOT NULL DEFAULT 1,
    reassignment_count  INT,
    reopen_count        INT,
    first_batch_id      VARCHAR(7),
    last_batch_id       VARCHAR(7),
    dw_updated_at       TIMESTAMP NOT NULL DEFAULT now()
);

-- Accumulating snapshot: one row per incident lifecycle, updated as later batches arrive
CREATE TABLE IF NOT EXISTS project_dw.fact_incident_lifecycle (
    incident_key                    BIGINT PRIMARY KEY,               -- same surrogate as fact_incident
    incident_number                 VARCHAR(15) NOT NULL UNIQUE,
    caller_id                       VARCHAR(30),
    reported_date_key               INT NOT NULL REFERENCES project_dw.dim_date(date_key),
    first_response_date_key         INT NOT NULL REFERENCES project_dw.dim_date(date_key),
    resolved_date_key               INT NOT NULL REFERENCES project_dw.dim_date(date_key),
    closed_date_key                 INT NOT NULL REFERENCES project_dw.dim_date(date_key),
    reported_time_key               INT NOT NULL REFERENCES project_dw.dim_time(time_key),
    first_response_time_key         INT NOT NULL REFERENCES project_dw.dim_time(time_key),
    location_key                    INT NOT NULL REFERENCES project_dw.dim_location(location_key),
    category_key                    INT NOT NULL REFERENCES project_dw.dim_category(category_key),
    severity_key                    INT NOT NULL REFERENCES project_dw.dim_severity(severity_key),
    current_status_key              INT NOT NULL REFERENCES project_dw.dim_status(status_key),
    current_team_key                INT NOT NULL REFERENCES project_dw.dim_response_team(team_key),
    contact_type_key                INT NOT NULL REFERENCES project_dw.dim_contact_type(contact_type_key),
    reported_at                     TIMESTAMP NOT NULL,
    first_response_at               TIMESTAMP,
    resolved_at                     TIMESTAMP,
    closed_at                       TIMESTAMP,
    incident_count                  SMALLINT NOT NULL DEFAULT 1,
    event_count                     INT,
    reassignment_count              INT,
    reopen_count                    INT,
    response_duration_minutes       INT,      -- NULL until first response
    resolution_duration_minutes     INT,      -- NULL while open
    closure_duration_minutes        INT,      -- NULL until closed
    response_to_resolution_minutes  INT,
    sla_compliance_count            SMALLINT, -- 1 = made SLA (flag on last event)
    resolved_count                  SMALLINT,
    open_count                      SMALLINT,
    last_batch_id                   VARCHAR(7),
    dw_updated_at                   TIMESTAMP NOT NULL DEFAULT now()
);

-- Transaction fact: one row per response activity (update event)
CREATE TABLE IF NOT EXISTS project_dw.fact_response_activity (
    activity_key                     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    incident_number                  VARCHAR(15) NOT NULL,    -- degenerate dim, drill-across to the other facts
    incident_key                     BIGINT,                  -- same conformed incident surrogate (no fact-to-fact FK)
    event_sequence_no                INT NOT NULL,
    sys_mod_count                    INT NOT NULL,
    activity_at                      TIMESTAMP NOT NULL,
    activity_date_key                INT NOT NULL REFERENCES project_dw.dim_date(date_key),
    activity_time_key                INT NOT NULL REFERENCES project_dw.dim_time(time_key),
    status_key                       INT NOT NULL REFERENCES project_dw.dim_status(status_key),
    team_key                         INT NOT NULL REFERENCES project_dw.dim_response_team(team_key),
    severity_key                     INT NOT NULL REFERENCES project_dw.dim_severity(severity_key),
    location_key                     INT NOT NULL REFERENCES project_dw.dim_location(location_key),
    category_key                     INT NOT NULL REFERENCES project_dw.dim_category(category_key),
    response_activity_count          SMALLINT NOT NULL DEFAULT 1,
    minutes_since_previous_activity  INT,
    batch_id                         VARCHAR(7) NOT NULL,
    CONSTRAINT uq_fact_activity UNIQUE (incident_number, sys_mod_count, activity_at)
);

CREATE INDEX IF NOT EXISTS ix_fi_date     ON project_dw.fact_incident (reported_date_key);
CREATE INDEX IF NOT EXISTS ix_fil_status  ON project_dw.fact_incident_lifecycle (current_status_key);
CREATE INDEX IF NOT EXISTS ix_fil_resdate ON project_dw.fact_incident_lifecycle (resolved_date_key);
CREATE INDEX IF NOT EXISTS ix_fra_batch   ON project_dw.fact_response_activity (batch_id);
CREATE INDEX IF NOT EXISTS ix_fra_date    ON project_dw.fact_response_activity (activity_date_key);
CREATE INDEX IF NOT EXISTS ix_fra_inc     ON project_dw.fact_response_activity (incident_number);

